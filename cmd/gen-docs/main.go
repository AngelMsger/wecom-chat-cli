// Site generation follows the MIT-licensed WeCom Channel CLI family pattern.
// Command gen-docs renders Markdown and a static GitHub Pages documentation site.
package main

import (
	"bytes"
	"fmt"
	"html"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/angelmsger/wecom-chat-cli/internal/app"
	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
	"github.com/yuin/goldmark"
	"github.com/yuin/goldmark/extension"
	"github.com/yuin/goldmark/parser"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func run() error {
	if len(os.Args) > 2 || len(os.Args) == 2 && os.Args[1] != "--check" {
		return fmt.Errorf("usage: gen-docs [--check]")
	}
	check := len(os.Args) > 1 && os.Args[1] == "--check"
	write := func(path string, data []byte) error {
		data = append(bytes.TrimSpace(data), '\n')
		if check {
			old, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(old, data) {
				return fmt.Errorf("%s is stale; run make docs", path)
			}
			return nil
		}
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return err
		}
		return os.WriteFile(path, data, 0644)
	}
	// Preserve the existing per-command Markdown URLs while adding the family site.
	tmp, err := os.MkdirTemp("", "wecom-chat-docs-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	root := app.NewRootCmd()
	root.DisableAutoGenTag = true
	if err := doc.GenMarkdownTree(root, tmp); err != nil {
		return err
	}
	files, err := filepath.Glob(filepath.Join(tmp, "*.md"))
	if err != nil {
		return err
	}
	expected := map[string]bool{}
	for _, file := range files {
		dst := filepath.Join("docs/cli", filepath.Base(file))
		expected[dst] = true
		data, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		if err := write(dst, data); err != nil {
			return err
		}
	}
	old, err := filepath.Glob("docs/cli/wecom-chat-cli*.md")
	if err != nil {
		return err
	}
	for _, file := range old {
		if !expected[file] {
			return fmt.Errorf("obsolete generated command: %s; remove it", file)
		}
	}
	var md, body bytes.Buffer
	md.WriteString("# CLI reference\n\nGenerated by `make docs`; edit the command tree, not this file.\n\n")
	body.WriteString(`<h1>Command reference</h1><p>Generated from the actual command tree. Every flag, one searchable surface.</p><label for="command-search">Find a command or flag</label><input id="command-search" class="command-search" type="search" placeholder="Try: task, approve, --dry-run"><p id="search-summary" class="search-summary" aria-live="polite"></p>`)
	var walk func(*cobra.Command)
	walk = func(c *cobra.Command) {
		usage := strings.TrimSpace(c.UsageString())
		fmt.Fprintf(&md, "## %s\n\n%s\n\n```text\n%s\n```\n\n", c.CommandPath(), c.Short, usage)
		fmt.Fprintf(&body, `<section class="command-section" id="%s"><h2>%s</h2><p>%s</p><pre><code>%s</code></pre></section>`, strings.ReplaceAll(c.CommandPath(), " ", "-"), html.EscapeString(c.CommandPath()), html.EscapeString(c.Short), html.EscapeString(usage))
		for _, child := range c.Commands() {
			walk(child)
		}
	}
	walk(app.NewRootCmd())
	if err := write("docs/cli/README.md", md.Bytes()); err != nil {
		return err
	}
	if err := write("docs/cli/index.html", shell("Command reference", "../", "cli/index.html", body.String())); err != nil {
		return err
	}
	pages := []struct{ source, target, title string }{
		{"README.md", "guide.html", "Operator guide"},
		{"docs/host-integration.md", "host-integration.html", "Host integration"},
		{"docs/security.md", "security.html", "Security model"},
		{"docs/technical-design.md", "technical-design.html", "Technical design"},
		{"docs/assessment.md", "assessment.html", "Assessment and scope"},
		{"docs/verification.md", "verification.html", "Verification"},
		{"docs/releasing.md", "releasing.html", "Release guide"},
	}
	renderer := goldmark.New(goldmark.WithExtensions(extension.GFM), goldmark.WithParserOptions(parser.WithAutoHeadingID()))
	links := map[string]string{"README.md": "guide.html", "CONTRIBUTING.md": "https://github.com/AngelMsger/wecom-chat-cli/blob/main/CONTRIBUTING.md", "docs/cli/README.md": "cli/index.html"}
	for _, p := range pages {
		links[p.source] = p.target
	}
	for _, file := range files {
		name := strings.TrimSuffix(filepath.Base(file), ".md")
		links["docs/cli/"+filepath.Base(file)] = "cli/index.html#" + strings.ReplaceAll(name, "_", "-")
	}
	re := regexp.MustCompile(`(href|src)="([^"#]+)(#[^"]*)?"`)
	for _, p := range pages {
		src, err := os.ReadFile(p.source)
		if err != nil {
			return err
		}
		var rendered bytes.Buffer
		if err = renderer.Convert(src, &rendered); err != nil {
			return err
		}
		content := re.ReplaceAllStringFunc(rendered.String(), func(s string) string {
			m := re.FindStringSubmatch(s)
			if strings.Contains(m[2], ":") || strings.HasPrefix(m[2], "/") {
				return s
			}
			resolved := filepath.ToSlash(filepath.Clean(filepath.Join(filepath.Dir(p.source), m[2])))
			dest, ok := links[resolved]
			if !ok {
				if strings.HasPrefix(resolved, "docs/") {
					dest = strings.TrimPrefix(resolved, "docs/")
				} else {
					dest = "https://github.com/AngelMsger/wecom-chat-cli/blob/main/" + resolved
				}
			}
			return m[1] + `="` + html.EscapeString(dest) + m[3] + `"`
		})
		if err = write("docs/"+p.target, shell(p.title, "", p.target, content)); err != nil {
			return err
		}
	}
	var sitemap strings.Builder
	sitemap.WriteString(`<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">`)
	for _, route := range append([]string{"", "cli/index.html"}, func() []string {
		var routes []string
		for _, p := range pages {
			routes = append(routes, p.target)
		}
		return routes
	}()...) {
		fmt.Fprintf(&sitemap, "<url><loc>https://angelmsger.github.io/wecom-chat-cli/%s</loc></url>", route)
	}
	sitemap.WriteString("</urlset>")
	return write("docs/sitemap.xml", []byte(sitemap.String()))
}
func shell(title, base, current, body string) []byte {
	var nav strings.Builder
	for _, p := range [][2]string{{"guide.html", "Operator guide"}, {"host-integration.html", "Host integration"}, {"cli/index.html", "Command reference"}, {"security.html", "Security model"}, {"technical-design.html", "Technical design"}, {"assessment.html", "Assessment"}, {"verification.html", "Verification"}, {"releasing.html", "Release guide"}} {
		selected := ""
		if current == p[0] {
			selected = ` aria-current="page"`
		}
		fmt.Fprintf(&nav, `<a href="%s%s"%s>%s</a>`, base, p[0], selected, p[1])
	}
	return []byte(fmt.Sprintf(`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="description" content="%s for WeCom Chat CLI: scoped smart-bot conversations and independently reviewed replies."><meta name="theme-color" content="#f4f8fc"><title>%s — WeCom Chat CLI</title><link rel="canonical" href="https://angelmsger.github.io/wecom-chat-cli/%s"><link rel="icon" href="%sassets/mark.svg"><link rel="stylesheet" href="%sassets/site.css"><script src="%sassets/site.js" defer></script></head><body class="docs-page"><a class="skip" href="#main">Skip to content</a><header class="nav wrap"><a class="brand" href="%sindex.html"><img src="%sassets/mark.svg" width="32" height="32" alt=""><span>WeCom Chat CLI</span></a><nav class="nav-links" aria-label="Main navigation"><a href="%shost-integration.html">Integration</a><a href="%sindex.html#explore">Explore</a><a href="https://github.com/AngelMsger/wecom-chat-cli">GitHub ↗</a></nav></header><main id="main" class="wrap doc-layout"><aside class="doc-sidebar"><span class="eyebrow">DOCUMENTATION / PRERELEASE</span>%s</aside><article class="doc-article">%s</article></main><footer class="wrap footer"><span>Built for agents. Designed for humans.</span><a href="%sindex.html">WeCom Chat CLI · MIT ↗</a></footer></body></html>`, html.EscapeString(title), html.EscapeString(title), current, base, base, base, base, base, base, base, nav.String(), body, base))
}
